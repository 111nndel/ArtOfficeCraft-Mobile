"""Independent OOXML fixture: 2000 body paragraphs, inherited/direct headings, table gap."""
import base64
import io
from pathlib import Path
import zipfile


def generate():
    ns = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'
    rel = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'
    paragraphs = []
    for i in range(2000):
        props, text = '', f'Body paragraph {i+1}. Text for a long document and lazy navigation.'
        if i == 0:
            props, text = '<w:pStyle w:val="LocalTitle"/>', 'Первый раздел'
        elif i == 999:
            props, text = '<w:pStyle w:val="LocalSubheading"/>', 'Средний раздел'
        elif i == 1999:
            props, text = '<w:outlineLvl w:val="2"/>', 'Последний раздел 😀'
        elif i == 50:
            props, text = '<w:pStyle w:val="LocalTitle"/><w:outlineLvl w:val="9"/>', 'Not a heading'
        paragraphs.append(f'<w:p><w:pPr>{props}</w:pPr><w:r><w:t>{text}</w:t></w:r></w:p>')
        if i == 10:
            paragraphs.append('<w:tbl><w:tblPr/><w:tblGrid><w:gridCol w:w="3000"/></w:tblGrid>'
                '<w:tr><w:tc><w:p><w:r><w:t>Table content is outside body navigation</w:t></w:r>'
                '</w:p></w:tc></w:tr></w:tbl>')
    parts = {
        '[Content_Types].xml': '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            '<Default Extension="xml" ContentType="application/xml"/>'
            '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
            '<Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/></Types>',
        '_rels/.rels': '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            f'<Relationship Id="doc" Type="{rel}/officeDocument" Target="word/document.xml"/></Relationships>',
        'word/document.xml': f'<w:document xmlns:w="{ns}"><w:body>' + ''.join(paragraphs) + '<w:sectPr/></w:body></w:document>',
        'word/_rels/document.xml.rels': '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            f'<Relationship Id="styles" Type="{rel}/styles" Target="styles.xml"/></Relationships>',
        'word/styles.xml': f'<w:styles xmlns:w="{ns}">'
            '<w:style w:type="paragraph" w:styleId="Normal" w:default="1"><w:name w:val="Normal"/></w:style>'
            '<w:style w:type="paragraph" w:styleId="BaseHeading"><w:name w:val="Base"/><w:basedOn w:val="Normal"/>'
            '<w:pPr><w:outlineLvl w:val="0"/></w:pPr></w:style>'
            '<w:style w:type="paragraph" w:styleId="LocalTitle"><w:name w:val="Локальный заголовок"/>'
            '<w:basedOn w:val="BaseHeading"/></w:style>'
            '<w:style w:type="paragraph" w:styleId="LocalSubheading"><w:name w:val="Локальный подраздел"/>'
            '<w:basedOn w:val="BaseHeading"/><w:pPr><w:outlineLvl w:val="1"/></w:pPr></w:style></w:styles>',
    }
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, 'w', zipfile.ZIP_DEFLATED) as archive:
        for name, content in parts.items():
            info = zipfile.ZipInfo(name, (2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, content)
    encoded = base64.b64encode(buffer.getvalue()).decode()
    return ("// Generated by tools/make_word_navigation_fixture.py. Test data only.\n"
        "import 'dart:convert';\nimport 'dart:typed_data';\n\n"
        "Uint8List wordNavigationFixture() => base64Decode(\n" +
        ''.join(f"  '{encoded[i:i+100]}'\n" for i in range(0, len(encoded), 100)) + ");\n")


if __name__ == '__main__':
    Path('integration_test/word_navigation_fixture.dart').write_text(generate())
