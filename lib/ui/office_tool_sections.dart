List<EditorSection> officeSections(
  String kind, {
  Map<String, EditorTool> overrides = const {},
  Map<String, List<EditorTool>> leading = const {},
  Set<String> exclude = const {},
}) => [
  for (final entry in officeToolLabels[kind]!.entries)
    EditorSection(entry.key, [
      ...?leading[entry.key],
      for (final label in entry.value)
        if (!exclude.contains(label))
          overrides[label] ?? EditorTool(label, _icon(label), pending: true),
    ]),
];

IconData _icon(String label) {
  if (label.contains('Шрифт') || label.contains('Текст')) {
    return Icons.text_fields;
  }
  if (label.contains('Масштаб') || label.contains('Поиск')) {
    return Icons.search;
  }
  if (label.contains('Цвет') || label.contains('Заливка')) {
    return Icons.format_color_fill;
  }
  if (label.contains('страниц') || label.contains('Страниц')) {
    return Icons.description_outlined;
  }
  if (label.contains('Комментар')) {
    return Icons.chat_bubble_outline;
  }
  if (label.contains('Сорт') || label.contains('Порядок')) {
    return Icons.sort;
  }
  if (label.contains('Таблиц') || label.contains('ячейк')) {
    return Icons.grid_on;
  }
  return Icons.tune;
}
